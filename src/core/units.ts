/**
 * Физические размеры книги и перевод их в единицы сцены.
 *
 * Одна единица сцены = 1 см. Книга получается ~15×21×2 — удобные числа для
 * камеры, света и теней, без возни с near/far.
 */

/** Миллиметры → единицы сцены. */
export const mm = (v: number) => v / 10;

export const PHYS = {
  /** Обрезной формат блока. Ближе всего к покетбуку / A5. */
  trimWidthMm: 148,
  trimHeightMm: 210,

  /**
   * Толщина одного листа при бумаге по умолчанию. Офсет 80 г/м² — 0.10 мм.
   * Отсюда берётся вся толщина тома, см. sheetsToThicknessMm.
   */
  sheetThicknessMm: 0.1,

  /** Переплётный картон. */
  coverThicknessMm: 2.4,

  /** Кант — насколько обложка выступает за блок с трёх сторон. */
  coverSquareMm: 3,

  /** Зазор между блоком и корешком у переплёта. */
  hingeMm: 6,
} as const;

/** Лист = две страницы. Нечётная страница добирается пустой оборотной. */
export const pagesToSheets = (pages: number) => Math.max(1, Math.ceil(pages / 2));

/**
 * Последний разворот книги.
 *
 * Развороты нумеруются листом, который на них слева: на развороте s слева
 * страница 2s−1, справа 2s. Отсюда и последний: чётное число страниц кончается
 * левой страницей отдельного разворота, нечётное — правой предыдущего. Считать
 * развороты просто по числу листов нельзя — последняя страница книги окажется
 * за краем, и до неё нельзя будет долистать.
 */
export const lastSpread = (pages: number) => Math.max(0, Math.floor(pages / 2));

/**
 * Плотность бумаги по умолчанию, г/м². Обычный книжный офсет.
 */
export const DEFAULT_GSM = 80;

/**
 * Толщина листа по плотности.
 *
 * Пухлость (объём на грамм) у бумаг разная — от 0.9 у мелованной до 1.6 у
 * пухлой книжной; берём одну усреднённую, при которой офсет 80 г/м² даёт те
 * самые 0.10 мм, из которых считалась толщина тома с M0. Ползунок плотности
 * (M6, §8) поэтому не переписывает историю: на дефолте всё осталось как было.
 */
export const sheetMm = (gsm: number) => gsm * 0.00125;

/**
 * Главная формула проекта: число страниц определяет физическую толщину тома.
 *
 * С M6 к нему добавился второй множитель — плотность бумаги. Она единственная
 * из настроек внешности меняет геометрию, и меняет её честно: страниц от
 * плотности не прибавляется, ключ вёрстки от неё не зависит, книга просто
 * становится толще — и на столе, и в ряду на полке.
 */
export const sheetsToThicknessMm = (sheets: number, gsm: number = DEFAULT_GSM) =>
  sheets * sheetMm(gsm);

/**
 * Толщина блока слева и справа в зависимости от прогресса чтения.
 * Именно это заставляет открытый том выглядеть «прочитанным наполовину».
 */
export function splitBlock(totalSheets: number, currentSheet: number) {
  const clamped = Math.min(Math.max(currentSheet, 0), totalSheets);
  return {
    leftMm: sheetsToThicknessMm(clamped),
    rightMm: sheetsToThicknessMm(totalSheets - clamped),
  };
}

/**
 * Разворот в книге: слева чётная страница предыдущего листа, справа — нечётная
 * текущего. Первый разворот показывает только правую: книга открывается на recto.
 *
 * Живёт в ядре, а не в сцене, хотя спрашивает об этом в первую очередь сцена.
 * Причина в том, кто ещё спрашивает: та же арифметика нужна шапке воркспейса,
 * чтобы написать «с. 114», а шапка есть и в плоском режиме, где сцены нет. Пока
 * функция лежала рядом с текстурами, за ней в первую загрузку приезжал three.
 */
export function spreadPages(sheet: number, pageCount: number) {
  const left = 2 * sheet - 1;
  const right = 2 * sheet;
  return {
    left: left >= 0 && left < pageCount ? left : null,
    right: right >= 0 && right < pageCount ? right : null,
  };
}
