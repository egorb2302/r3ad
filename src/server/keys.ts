/**
 * Имена в хранилище.
 *
 * Вынесены из `blob.ts` отдельно ради одного: у хранилища две реализации —
 * файловая и Vercel Blob, — и обеим нужны одни и те же префиксы, а модуль с
 * выбором реализации импортирует их обе. Держи префиксы там же, где выбор, и
 * получился бы цикл импортов, который в ESM разрешается «неопределённым» на
 * этапе инициализации, то есть падением при первом же обращении.
 */

export const ASSET_PREFIX = 'assets/';
export const SNAPSHOT_PREFIX = 'snapshots/';
/** Реестр снапшотов, когда он лежит в том же блобе (см. vercelBlob.ts). */
export const META_PREFIX = 'meta/';

/** Ключ ассета — его хэш. Ключ манифеста — версия внутри снапшота. */
export const assetKey = (hash: string) => `${ASSET_PREFIX}${hash}`;
export const snapshotKey = (id: string, version: number) =>
  `${SNAPSHOT_PREFIX}${id}/${version}.json`;

