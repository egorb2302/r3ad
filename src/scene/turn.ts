'use client';

/**
 * Движение переворачивающегося листа.
 *
 * Отдельно от React намеренно: прогресс переворота меняется каждый кадр, и
 * будь он состоянием компонента, каждый кадр стоил бы полного прохода
 * реконсиляции. Здесь он живёт в обычном изменяемом объекте, который читает
 * useFrame и пишет прямо в юниформы.
 *
 * Пружина, а не твин. Разница не косметическая: у твина нет понятия скорости,
 * поэтому отпущенный на середине лист может только доиграть заранее заданную
 * кривую. Пружина принимает скорость от пальца — резкий бросок доносит лист до
 * конца, вялый отпускает обратно, и это решение принимает физика, а не таймер
 * (SPEC §7.2, «инерция»).
 */

import { motionPrefs } from './motionPrefs';

export interface TurnMotion {
  /** 0 — лист лежит справа, 1 — слева. */
  t: number;
  target: number;
  velocity: number;
  dragging: boolean;
}

/**
 * Единственный лист в воздухе.
 *
 * Модульный синглтон, а не состояние компонента, — и это не срезание угла.
 * Переворачивающийся лист в книге ровно один: пока он летит, следующий начаться
 * не может, а заявка на новый переворот сначала досчитывает текущий (см.
 * requestTurn в сторе). Держать это в React значило бы гонять реконсиляцию
 * шестьдесят раз в секунду ради числа, которое читает только кадровый цикл.
 */
export const motion: TurnMotion = { t: 0, target: 0, velocity: 0, dragging: false };

/**
 * Поставить лист в начальную позу.
 *
 * Цель задаётся сразу, а не «когда-нибудь потом»: пружина, у которой t уже
 * равно target, считает себя успокоившейся на первом же кадре, и переворот
 * заканчивается, не начавшись. Для перетаскивания цель совпадает с началом
 * намеренно — её выставит палец, когда лист отпустят.
 */
export function resetMotion(from: number, target: number, dragging: boolean) {
  motion.t = from;
  motion.target = target;
  motion.velocity = 0;
  motion.dragging = dragging;
}

/** Пружина чуть жёстче критического затухания: лист доходит быстро и без отката. */
const STIFFNESS = 190;
const DAMPING = 2 * Math.sqrt(STIFFNESS) * 0.92;

/** Насколько далеко «бросок» продлевает движение при выборе, куда падать. */
const FLING = 0.14;

/**
 * Потолок скорости листа, оборотов в секунду.
 *
 * Мышь умеет пролететь весь экран за один кадр, и честно посчитанная по такому
 * кадру скорость выходит в десятки переворотов в секунду. Ограничитель делает
 * бросок предсказуемым: как ни маши рукой, лист долистывает примерно за то же
 * время.
 */
export const MAX_SPEED = 7;

/** Шаг пружины. Возвращает true, когда лист успокоился. */
export function stepMotion(motion: TurnMotion, dt: number): boolean {
  if (motion.dragging) return false;

  /*
   * При «поменьше движения» лист не летит, а оказывается на месте. Заметьте,
   * что перетаскивание проверено выше и сюда не доходит: настройка про
   * анимации, которые происходят сами, а не про то, что человек ведёт пальцем.
   */
  if (motionPrefs.instant) {
    motion.t = motion.target;
    motion.velocity = 0;
    return true;
  }

  // Кадр мог быть длинным (вкладка уходила в фон) — иначе пружина взорвётся.
  const step = Math.min(dt, 1 / 30);

  const accel = -STIFFNESS * (motion.t - motion.target) - DAMPING * motion.velocity;
  motion.velocity += accel * step;
  motion.t += motion.velocity * step;

  /*
   * Жёсткий упор на концах. Лист лежит на стопке и провернуться дальше не
   * может: без ограничителя резкий бросок уносит θ за π, и страница на глазах
   * уходит сквозь левый блок вниз. Скорость на упоре гасится только та, что
   * толкает наружу, — обратно лист по-прежнему волен уехать.
   */
  if (motion.t < 0) {
    motion.t = 0;
    motion.velocity = Math.max(0, motion.velocity);
  } else if (motion.t > 1) {
    motion.t = 1;
    motion.velocity = Math.min(0, motion.velocity);
  }

  if (Math.abs(motion.t - motion.target) < 0.002 && Math.abs(motion.velocity) < 0.05) {
    motion.t = motion.target;
    motion.velocity = 0;
    return true;
  }
  return false;
}

/**
 * Куда лист полетит после того, как его отпустили.
 * Учитываем не только положение, но и скорость: короткий резкий бросок от
 * середины должен долистывать, а не откатываться.
 */
export function releaseTarget(motion: TurnMotion): number {
  return motion.t + motion.velocity * FLING > 0.5 ? 1 : 0;
}

/**
 * Какой лист переворачивается и куда.
 *
 * Пара всегда описывается нижним листом `a`: вперёд с листа s и назад с s+1 —
 * это один и тот же физический лист, у которого лицо это страница 2a, а оборот
 * 2a+1. Единое описание избавляет сцену от ветвления по направлению: меняются
 * только концы отрезка, по которому едет пружина.
 */
export interface TurnPlan {
  a: number;
  /** Начало движения: 0 — лист лежит справа, 1 — слева. */
  from: number;
  /** Значение t, при котором переворот считается состоявшимся. */
  commitAt: number;
  /** Лист, на который переходим, если состоялся. */
  toSheet: number;
}

/**
 * Границей служит последний разворот, а не число листов: у книги с чётным
 * числом страниц последняя лежит на отдельном развороте, где справа уже ничего
 * нет (см. lastSpread в core/units). Считать по листам значило бы не доносить
 * читателя до последней страницы ровно на один разворот.
 */
export function planTurn(
  currentSheet: number,
  lastSheet: number,
  dir: 1 | -1,
): TurnPlan | null {
  if (dir > 0) {
    if (currentSheet >= lastSheet) return null;
    return { a: currentSheet, from: 0, commitAt: 1, toSheet: currentSheet + 1 };
  }
  if (currentSheet <= 0) return null;
  return { a: currentSheet - 1, from: 1, commitAt: 0, toSheet: currentSheet - 1 };
}

/** Поза листа под рукой в дев-сборке: в сторе её нет, она живёт в кадре. */
if (process.env.NODE_ENV !== 'production') {
  (globalThis as { __r3adMotion?: TurnMotion }).__r3adMotion = motion;
}
