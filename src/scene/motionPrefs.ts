'use client';

/**
 * Одно значение на всю сцену: анимировать или показывать сразу.
 *
 * `prefers-reduced-motion` — не «выключить красоту». Для части людей движущаяся
 * картинка это тошнота и головокружение, и системная настройка говорит именно
 * об этом. Отсюда правило: при включённом флаге ни одно движение не отменяется
 * как действие — страница всё так же переворачивается, книга всё так же уезжает
 * на полку, — но происходит это мгновенно, без промежуточных кадров.
 *
 * Флаг лежит в модуле, а не в сторе, по той же причине, что и сама анимация
 * (см. turn.ts): его читают из кадрового цикла, а не из рендера React.
 */
export const motionPrefs = { instant: false };

export function setInstantMotion(instant: boolean) {
  motionPrefs.instant = instant;
}

/**
 * Длительность с поправкой на настройку.
 *
 * Ноль сюда возвращать нельзя: на него делят и переезд камеры, и полёт. Кадр —
 * достаточно мало, чтобы движение не читалось, и достаточно много, чтобы
 * арифметика осталась арифметикой.
 */
export const span = (seconds: number) => (motionPrefs.instant ? 1 / 60 : seconds);
