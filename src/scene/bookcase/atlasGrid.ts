/**
 * Сетка атласа корешков.
 *
 * Одни числа, без three и без холста: их спрашивает и тот, кто печатает атлас,
 * и тот, кто ставит инстансы, и — главное — инспектор, который просто пишет
 * «сорок из шестидесяти четырёх». Инспектор есть и в плоском режиме, где сцены
 * нет вовсе, и тянуть за этой цифрой рендер было бы дорого (см. §16, M7).
 */
export const ATLAS = 2048;
export const CELL_W = 128;
export const CELL_H = 512;

export const COLS = ATLAS / CELL_W;
const ROWS = ATLAS / CELL_H;

/**
 * Сколько корешков помещается в атлас — столько же томов помещается на
 * стеллаж. Лишние уходят в overflow, см. §21.9.
 */
export const SPINE_CAPACITY = COLS * ROWS;
